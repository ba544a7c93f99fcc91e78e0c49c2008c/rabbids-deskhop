#!/usr/bin/env python3
"""
Generate a DeskHop USB identity profile that replicates real USB devices
(e.g. the keyboard and mouse you are going to use), read from Linux sysfs.

  # 1. Plug the keyboard/mouse into this Linux machine and list devices
  ./clone_usb_identity.py --list

  # 2. Generate a profile: board A clones the keyboard, board B the mouse
  ./clone_usb_identity.py --a 046d:c31c --b 046d:c077 -o my_profile.cmake

  # 3. Build
  cmake -C misc/usb_identity/my_profile.cmake -S . -B build && cmake --build build

A device can be given as VID:PID or as its sysfs bus id (e.g. 1-2.3) when two
identical devices are plugged in. Omit --a or --b to keep that board's defaults.
"""

import argparse
import os
import sys

SYSFS = "/sys/bus/usb/devices"
MAX_STR = 31  # firmware caps string descriptors at 31 chars


def read_attr(dev, name):
    try:
        with open(os.path.join(SYSFS, dev, name), encoding="utf-8", errors="replace") as f:
            return f.read().strip()
    except OSError:
        return ""


def list_devices():
    devs = []
    for dev in sorted(os.listdir(SYSFS)):
        if ":" in dev:  # interfaces, not devices
            continue
        vid = read_attr(dev, "idVendor")
        if not vid:
            continue
        devs.append({
            "busid": dev,
            "vid": vid.lower(),
            "pid": read_attr(dev, "idProduct").lower(),
            "bcd": read_attr(dev, "bcdDevice").lower() or "0100",
            "manufacturer": read_attr(dev, "manufacturer"),
            "product": read_attr(dev, "product"),
            "serial": read_attr(dev, "serial"),
        })
    return devs


def find_device(devs, spec):
    spec = spec.lower()
    if ":" in spec and "-" not in spec:
        vid, pid = spec.split(":", 1)
        matches = [d for d in devs if d["vid"] == vid.zfill(4) and d["pid"] == pid.zfill(4)]
    else:
        matches = [d for d in devs if d["busid"] == spec]
    if not matches:
        sys.exit(f"error: no USB device matches '{spec}' (use --list)")
    if len(matches) > 1:
        ids = ", ".join(d["busid"] for d in matches)
        sys.exit(f"error: '{spec}' matches several devices ({ids}); pass the bus id instead")
    return matches[0]


def sanitize(value, label):
    """Keep printable ASCII without quote/backslash, max 31 chars (firmware limits)."""
    clean = "".join(c for c in value if " " <= c <= "~" and c not in "\"\\")
    if len(clean) > MAX_STR:
        clean = clean[:MAX_STR]
    if clean != value:
        print(f"warning: {label} '{value}' adjusted to '{clean}'", file=sys.stderr)
    return clean


def board_block(board, dev, keep_serial):
    serial = sanitize(dev["serial"], f"board {board} serial") if keep_serial else ""
    product = sanitize(dev["product"], f"board {board} product")
    fields = [
        ("VID", "0x" + dev["vid"].upper()),
        ("PID", "0x" + dev["pid"].upper()),
        ("BCD", "0x" + dev["bcd"].upper()),
        ("MANUFACTURER", sanitize(dev["manufacturer"], f"board {board} manufacturer")),
        ("PRODUCT", product),
        ("SERIAL", serial),
        ("HELPER", product),
    ]
    lines = [f"# Board {board}: cloned from {dev['busid']} "
             f"{dev['vid']}:{dev['pid']} {dev['manufacturer']} {dev['product']}".rstrip()]
    for name, value in fields:
        lines.append(f'set(DH_USB_{board}_{name:<12} "{value}" CACHE STRING "")')
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--list", action="store_true", help="list connected USB devices")
    ap.add_argument("--a", metavar="DEV", help="device to clone on board A (VID:PID or bus id)")
    ap.add_argument("--b", metavar="DEV", help="device to clone on board B (VID:PID or bus id)")
    ap.add_argument("--serial", action="store_true",
                    help="also copy the serial number (default: use the Pico's unique ID)")
    ap.add_argument("-o", "--output", help="output .cmake profile (default: stdout)")
    args = ap.parse_args()

    if not os.path.isdir(SYSFS):
        sys.exit(f"error: {SYSFS} not found (this script needs Linux)")

    devs = list_devices()

    if args.list or not (args.a or args.b):
        print(f"{'BUS ID':<10} {'VID:PID':<10} {'BCD':<5} MANUFACTURER / PRODUCT")
        for d in devs:
            print(f"{d['busid']:<10} {d['vid']}:{d['pid']}  {d['bcd']:<5} {d['manufacturer']} / {d['product']}")
        return

    blocks = ["## DeskHop USB identity profile generated by clone_usb_identity.py",
              "## Build: cmake -C <this file> -S . -B build && cmake --build build", ""]
    for board, spec in (("A", args.a), ("B", args.b)):
        if spec:
            blocks.append(board_block(board, find_device(devs, spec), args.serial))
            blocks.append("")
    text = "\n".join(blocks)

    if args.output:
        with open(args.output, "w", encoding="ascii") as f:
            f.write(text)
        print(f"wrote {args.output}", file=sys.stderr)
    else:
        print(text)


if __name__ == "__main__":
    main()
